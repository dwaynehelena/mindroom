"""P8 Phase 2 LIVE-FIRE proof.

Runs the ops-autopilot orchestrator IN-PROCESS against the live Matrix runtime:

  1. Builds the live approval store + Matrix client (token from
     ``~/.mindroom/mindroom_data/matrix_state.yaml``, loopback
     ``http://127.0.0.1:8008``).
  2. Composes a SHORT brief (small body, well under 4 KiB) and delivers it
     UNGATED to the portal room ``!CzLMONAFcsUmQXAVZw:localhost``, capturing the
     delivered brief event id.
  3. Surfaces ONE ARIP-gated suggested action (``gh_action``, Approve/Deny from
     ``@dwayne:localhost``) by posting an ``io.mindroom.tool_approval`` card,
     capturing the ARIP request event id.

The one-off schedule (~5 min out) that fires the in-process pipeline is
registered separately through the real scheduler backend.
"""
from __future__ import annotations

